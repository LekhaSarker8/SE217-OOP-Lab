public class DataType_And_Variables {
    public static void main(String[] args) {
        // Declare variables of different data types
        int myInt = 8; // Integer
        double myDouble = 3.99; // Double
        char myChar = 'I'; // Character
        boolean myBoolean = true; // Boolean
        String myString = "Hello, Java!"; // String
        long myLong = 100000L; // Long

        // Print the values of the variables
        System.out.println("Integer: " + myInt);
        System.out.println("Double: " + myDouble);
        System.out.println("Character: " + myChar);
        System.out.println("Boolean: " + myBoolean);
        System.out.println("String: " + myString);
        System.out.println("Long: " + myLong);

        //variables
        int x = 3000;

        System.out.println("Stipend of student-1: " + (3.56 * x));
        System.out.println("Stipend of student-2: " + (3.78 * x));
        System.out.println("Stipend of student-3: " + (4.00 * x));
        System.out.println("Total stipend: " + ((3.56 * x) + (3.78 * x) + (4.00 * x)));
    }
}